func TestFFTRoundTrip(t *testing.T) {
	f := newFFT512()
	in := make([]float32, nfft)
	rng := rand.New(rand.NewSource(7))
	for i := range in {
		in[i] = float32(rng.NormFloat64())
	}
	spec := make([]float32, bins*2)
	out := make([]float32, nfft)
	f.forward(in, spec)
	f.inverse(spec, out)
	for i := range in {
		if d := math.Abs(float64(in[i] - out[i])); d > 1e-4 {
			t.Fatalf("sample %d: in=%v out=%v", i, in[i], out[i])
		}
	}
}

// Analysis and synthesis windows must reconstruct exactly through overlap-add,
// or the enhancer would add its own amplitude ripple on top of the model.
func TestWindowOverlapAddIsUnity(t *testing.T) {
	for i := 0; i < hop; i++ {
		sum := window[i]*window[i] + window[i+hop]*window[i+hop]
		if d := math.Abs(float64(sum) - 1); d > 1e-6 {
			t.Fatalf("index %d: window squares sum to %v", i, sum)
		}
	}
}

func readPCM(t *testing.T, path string) []int16 {
	t.Helper()
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	out := make([]int16, len(raw)/2)
	for i := range out {
		out[i] = int16(binary.LittleEndian.Uint16(raw[2*i:]))
	}
	return out
}

// The Go port must reproduce, sample for sample, what onnxruntime + numpy
// produce for the same model and framing (testdata generated by the reference
// implementation; noisy.pcm is a synthesized Mandarin utterance mixed with
// synthetic street noise). Set DENOISE_ONNXRUNTIME_LIB to run it.
func TestDenoiserMatchesReference(t *testing.T) {
	lib := os.Getenv("DENOISE_ONNXRUNTIME_LIB")
	if lib == "" {
		t.Skip("DENOISE_ONNXRUNTIME_LIB not set")
	}
	if err := Init(lib, 1); err != nil {
		t.Fatalf("init: %v", err)
	}
	noisy := readPCM(t, "testdata/noisy.pcm")
	want := readPCM(t, "testdata/enhanced.pcm")

	d := New()
	if d == nil {
		t.Fatal("New returned nil after a successful Init")
	}
	defer d.Close()
	// The reference vector is the model on its own, without the share of dry
	// signal production keeps.
	d.mix = 1

	const frameSamples = 320 // 20 ms, the transport's frame size
	var got []int16
	for i := 0; i+frameSamples <= len(noisy); i += frameSamples {
		got = append(got, d.Process(noisy[i:i+frameSamples])...)
	}
	// Output lags the input by the one hop of silence the enhancer starts with.
	if len(got) <= hop {
		t.Fatalf("only %d samples out", len(got))
	}
	for i := 0; i < hop; i++ {
		if got[i] != 0 {
			t.Fatalf("expected a hop of leading silence, got[%d]=%d", i, got[i])
		}
	}
	got = got[hop:]

	n := len(got)
	if n > len(want) {
		n = len(want)
	}
	var diff, energy float64
	for i := 0; i < n; i++ {
		e := float64(got[i]) - float64(want[i])
		if math.Abs(e) > 2 {
			t.Fatalf("sample %d: got %d want %d", i, got[i], want[i])
		}
		diff += e * e
		energy += float64(want[i]) * float64(want[i])
	}
	if snr := 10 * math.Log10(energy/(diff+1e-9)); snr < 70 {
		t.Fatalf("only %.1f dB against the reference", snr)
	}
}

func BenchmarkDenoiserProcess(b *testing.B) {
	lib := os.Getenv("DENOISE_ONNXRUNTIME_LIB")
	if lib == "" {
		b.Skip("DENOISE_ONNXRUNTIME_LIB not set")
	}
	if err := Init(lib, 1); err != nil {
		b.Fatalf("init: %v", err)
	}
	d := New()
	if d == nil {
		b.Fatal("New returned nil")
	}
	defer d.Close()
	frame := make([]int16, 320)
	for i := range frame {
		frame[i] = int16(1000 * math.Sin(float64(i)/8))
	}
	b.ResetTimer()
	for i := 0; i < b.N; i++ {
		d.Process(frame)
	}
	// Frames are 20 ms of audio: ns/op ÷ 2e7 is the real-time factor.
}
